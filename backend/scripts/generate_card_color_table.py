"""Regenerate `mtg_analyzer/models/cards/card_color_table.py`.

RULE 204 colour indicators (and any other face whose colour is not what its
mana cost + devoid/colour-CDA text gives) are not stored on `Card`, so the
engine reads them from a checked-in table keyed by face name. This script
compares Scryfall's per-face ``colors`` in the raw store (opened read-only)
with `card_colors.derived_colors` and writes every face the derivation gets
wrong. Rerun it after `update_card_pool.py` brings in new cards:

    python backend/scripts/generate_card_color_table.py          # rewrite the table
    python backend/scripts/generate_card_color_table.py --check  # exit 1 if stale
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from mtg_analyzer.models.cards.card_colors import derived_colors  # noqa: E402

RAW_DB = BACKEND / "data" / "scryfall_raw.db"
TABLE_PATH = BACKEND / "mtg_analyzer" / "models" / "cards" / "card_color_table.py"

#: Scryfall objects that are not real cards: their colours come from the creating effect (tokens, RULE 111.4)
#: or are irrelevant to play.
SKIP_LAYOUTS = frozenset({"token", "double_faced_token", "emblem", "art_series", "planar", "scheme", "vanguard",
                          # Each half is coloured by its own cost (RULE 709.3 / 715.2); Scryfall's per-face `colors`
                          # there describe the combined card, so they must not enter the table.
                          "split", "adventure", "prepare"})
SKIP_SET_TYPES = frozenset({"memorabilia", "token"})
_ORDER = "WUBRG"


class FaceView:
    """The `Card` fields `derived_colors` reads, taken from one Scryfall face."""

    def __init__(self, data: dict, face: dict, multi: bool) -> None:
        self.name = face.get("name", data["name"])
        self.mana_cost_string = (face.get("mana_cost") if multi else data.get("mana_cost")) or ""
        self.oracle_text = face.get("oracle_text", "") or ""
        self.keywords = data.get("keywords") or []


def face_truth(data: dict, face: dict, multi: bool):
    colors = face.get("colors") if multi else data.get("colors")
    if colors is None:
        colors = data.get("colors")
    return None if colors is None else frozenset(colors)


def iter_faces(con: sqlite3.Connection):
    for (raw,) in con.execute("SELECT json FROM raw_cards"):
        data = json.loads(raw)
        if data.get("layout") in SKIP_LAYOUTS or data.get("set_type") in SKIP_SET_TYPES:
            continue
        faces = data.get("card_faces") or [data]
        multi = bool(data.get("card_faces"))
        for face in faces:
            yield data, face, multi


def build_table() -> dict[str, str]:
    con = sqlite3.connect(f"file:{RAW_DB}?mode=ro", uri=True)
    table: dict[str, str] = {}
    conflicts: set[str] = set()
    for data, face, multi in iter_faces(con):
        truth = face_truth(data, face, multi)
        view = FaceView(data, face, multi)
        if truth is None or derived_colors(view) == truth:
            continue
        letters = "".join(c for c in _ORDER if c in truth)
        if table.get(view.name, letters) != letters:
            conflicts.add(view.name)
        table[view.name] = letters
    # A face name shared by different cards with different colours (Un-set gags, reused
    # names) cannot be resolved by name; leave it to the cost-derived colours.
    for name in sorted(conflicts):
        print(f"skipped ambiguous face name {name!r}", file=sys.stderr)
        del table[name]
    return table


def render(table: dict[str, str]) -> str:
    lines = [
        '"""GENERATED by scripts/generate_card_color_table.py - do not edit by hand.',
        "",
        "Face name -> WUBRG letters for faces whose colour (RULE 204 colour indicator",
        "or a CDA the text pass misses) differs from `card_colors.derived_colors`.",
        '"""',
        "",
        "FACE_COLORS: dict[str, str] = {",
    ]
    lines += [f"    {json.dumps(name, ensure_ascii=False)}: {json.dumps(letters)}," for name, letters in sorted(table.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the checked-in table is stale")
    args = parser.parse_args()
    text = render(build_table())
    if args.check:
        sys.exit(0 if TABLE_PATH.exists() and TABLE_PATH.read_text(encoding="utf-8") == text else 1)
    TABLE_PATH.write_text(text, encoding="utf-8")
    print(f"Wrote {TABLE_PATH} ({text.count(chr(10)) - 8} faces).")


if __name__ == "__main__":
    main()
