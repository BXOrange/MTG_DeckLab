"""Printed (actual) colours of a card, kept apart from Commander colour identity.

RULE 105.2 / 202.2: an object's colour comes from its mana cost (or a colour
indicator, RULE 204), never from rules-text mana symbols. RULE 903.4 colour
identity is a deck-building concept that *does* count those symbols (a Forest
has green identity but is colourless), so in-game consumers must read these
helpers (or `GameObject.colors`, which layers RULE 613.4 on top), while deck
validation and Commander-only effects stay on ``Card.color_identity``.

``Card`` has no stored colour/indicator field (its schema hash gates the card
cache), so the printed colours are derived here from data it does keep, plus a
generated table of faces whose colour is not what their cost gives (colour
indicators, RULE 204; see `card_color_table.py`, regenerated by
`scripts/generate_card_color_table.py`).
"""

from __future__ import annotations

import re
from typing import Any, Iterable, Optional

from ..mana.mana_cost import ManaCost

#: Attribute a copy effect stamps on its modified `Card` ("...except it's blue",
#: RULE 707.9b) so the overridden colours beat the unchanged mana cost.
COLOR_OVERRIDE_ATTR = "printed_colors_override"

#: RULE 702.114a: Devoid is a characteristic-defining ability, so it applies in
#: every zone and makes the object colourless.
_DEVOID_LINE = re.compile(r"(?im)^\s*devoid\b")

#: RULE 604.3 / 105.2: a colour-defining characteristic-defining ability written
#: as its own sentence about the object itself ("Transguild Courier is all
#: colors.", "Ghostfire is colorless."); applies in every zone.
_CDA_COLOR_LINE = re.compile(
    r"(?im)^(?!(?:enchanted|equipped|target|each|all|other|creatures?|you|it|that|those)\b)"
    r"[^,.:;\n]{1,60} is (?P<what>all colors|every color|colorless)(?:\.|\s*$)"
)

ALL_COLORS: frozenset[str] = frozenset("WUBRG")


def _has_devoid(card: Any) -> bool:
    if any(str(k).lower() == "devoid" for k in (getattr(card, "keywords", None) or ())):
        return True
    return bool(_DEVOID_LINE.search(getattr(card, "oracle_text", "") or ""))


def derived_colors(card: Any) -> frozenset[str]:
    """Colours from the rules text and mana cost alone (no indicator table).

    Used by the table generator to find the faces this derivation gets wrong;
    ``printed_colors`` is the entry point everything else uses."""
    if _has_devoid(card):
        return frozenset()
    match = _CDA_COLOR_LINE.search(getattr(card, "oracle_text", "") or "")
    if match:
        return frozenset() if match.group("what") == "colorless" else ALL_COLORS
    cost = (getattr(card, "mana_cost_string", "") or "").strip()
    # RULE 202.2: colour is that of the mana symbols in the cost (hybrid halves
    # and Phyrexian colours included, generic/colourless none); RULE 202.2b: no
    # cost and no indicator means colourless.
    return frozenset(ManaCost.parse(cost).color_identity) if cost else frozenset()


def _table_colors(card: Any) -> Optional[frozenset[str]]:
    from .card_color_table import FACE_COLORS

    name = getattr(card, "name", "") or ""
    for key in (name, name.split(" // ")[0]):
        if key in FACE_COLORS:
            return frozenset(FACE_COLORS[key])
    return None


def printed_colors(card: Any) -> frozenset[str]:
    """The colours a printed `Card` has before any layer-5 effect (RULE 105.2)."""
    override = getattr(card, COLOR_OVERRIDE_ATTR, None)
    if override is not None:
        return frozenset(override)
    if getattr(card, "is_token", False):
        # RULE 111.4: a token's colours come from the effect that created it;
        # token `Card`s record them as their colour identity.
        return frozenset(getattr(card, "color_identity", None) or ())
    known = _table_colors(card)
    if known is not None:
        return known  # RULE 204 colour indicator (or a CDA the text pass would also find)
    return derived_colors(card)


def effective_colors(obj_or_card: Any) -> frozenset[str]:
    """Colours of a `GameObject` (layer 5 applied) or of a bare `Card`."""
    if hasattr(obj_or_card, "card") and hasattr(obj_or_card, "instance_id"):
        return frozenset(obj_or_card.colors)
    return printed_colors(obj_or_card)


def with_color_override(card: Any, colors: Iterable[str]) -> Any:
    """Stamp copiable colours onto a copy's `Card` (RULE 707.9b) and return it."""
    setattr(card, COLOR_OVERRIDE_ATTR, frozenset(colors))
    return card
